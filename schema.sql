CREATE DATABASE IF NOT EXISTS resume_ai CHARACTER SET utf8mb4;
USE resume_ai;
CREATE TABLE users(
  id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL,
  email VARCHAR(120) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
  role ENUM('student','admin') DEFAULT 'student', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE analyses(
  id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, filename VARCHAR(255),
  target_role VARCHAR(120), score INT, result JSON, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE);
CREATE TABLE resources(
  id INT AUTO_INCREMENT PRIMARY KEY, kind VARCHAR(40), title VARCHAR(160), url VARCHAR(255),
  skill VARCHAR(80));
